export async function generateIncidentReport(incident) {
  if (!window.jspdf) {
    console.error("jsPDF not loaded");
    return;
  }
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF();
  
  // Header
  doc.setFillColor(30, 30, 45);
  doc.rect(0, 0, 210, 40, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.text('CivicEye AI', 20, 20);
  doc.setFontSize(14);
  doc.text('Incident Report', 20, 30);
  
  // Incident Details
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(16);
  doc.setFont(undefined, 'bold');
  doc.text('Incident Details', 20, 60);
  
  doc.setFontSize(12);
  doc.setFont(undefined, 'normal');
  const startY = 70;
  const lineSpacing = 8;
  
  doc.text(`Type: ${(incident.type || 'Unknown').replace(/_/g, ' ')}`, 20, startY);
  doc.text(`Severity: ${incident.severity || 'UNKNOWN'}`, 20, startY + lineSpacing);
  const confidenceStr = incident.confidence ? `${Math.round(incident.confidence * 100)}%` : 'N/A';
  doc.text(`Confidence: ${confidenceStr}`, 20, startY + lineSpacing * 2);
  const volumeStr = incident.volume_estimate_tonnes ? `${incident.volume_estimate_tonnes.toFixed(2)} tonnes` : 'N/A';
  doc.text(`Estimated Volume: ${volumeStr}`, 20, startY + lineSpacing * 3);
  
  // Location & Timestamp
  doc.setFontSize(16);
  doc.setFont(undefined, 'bold');
  doc.text('Location & Time', 20, startY + lineSpacing * 5);
  
  doc.setFontSize(12);
  doc.setFont(undefined, 'normal');
  const locY = startY + lineSpacing * 6;
  doc.text(`Coordinates: ${incident.lat || 'N/A'}, ${incident.lng || 'N/A'}`, 20, locY);
  doc.text(`Ward Estimation: ${incident.ward || 'Unknown'}`, 20, locY + lineSpacing);
  
  const firstSeenStr = incident.first_seen ? new Date(incident.first_seen).toLocaleString() : new Date().toLocaleString();
  const lastSeenStr = incident.last_seen ? new Date(incident.last_seen).toLocaleString() : firstSeenStr;
  doc.text(`First Seen: ${firstSeenStr}`, 20, locY + lineSpacing * 2);
  doc.text(`Last Seen: ${lastSeenStr}`, 20, locY + lineSpacing * 3);
  
  // AI Analysis
  doc.setFontSize(16);
  doc.setFont(undefined, 'bold');
  doc.text('AI Analysis & Recommendations', 20, locY + lineSpacing * 5);
  
  doc.setFontSize(12);
  doc.setFont(undefined, 'normal');
  let textY = locY + lineSpacing * 6;
  
  const descText = doc.splitTextToSize(`Description: ${incident.description || 'No description available.'}`, 170);
  doc.text(descText, 20, textY);
  textY += descText.length * 6 + 5;
  
  const actionText = doc.splitTextToSize(`Recommended Action: ${incident.recommended_action || 'Needs manual review.'}`, 170);
  doc.text(actionText, 20, textY);
  
  // Footer
  doc.setFontSize(10);
  doc.setTextColor(150, 150, 150);
  doc.text('Generated by CivicEye AI for Mysuru City Corporation', 105, 280, { align: 'center' });
  
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  doc.save(`CivicEye_Report_${timestamp}.pdf`);
}

export async function generateSummaryReport(incidents, stats) {
  if (!window.jspdf) return;
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF();
  
  doc.setFillColor(30, 30, 45);
  doc.rect(0, 0, 210, 40, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.text('CivicEye AI', 20, 20);
  doc.setFontSize(14);
  doc.text('Summary Report', 20, 30);
  
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(16);
  doc.setFont(undefined, 'bold');
  doc.text('Executive Summary', 20, 60);
  
  doc.setFontSize(12);
  doc.setFont(undefined, 'normal');
  doc.text(`Total Incidents: ${stats?.total || incidents?.length || 0}`, 20, 75);
  doc.text(`Critical Issues: ${stats?.critical || 0}`, 20, 85);
  doc.text(`Resolved: ${stats?.resolved || 0}`, 20, 95);
  
  // Footer
  doc.setFontSize(10);
  doc.setTextColor(150, 150, 150);
  doc.text('Generated by CivicEye AI for Mysuru City Corporation', 105, 280, { align: 'center' });
  
  doc.save(`CivicEye_Summary_${Date.now()}.pdf`);
}

export default { generateIncidentReport, generateSummaryReport };
